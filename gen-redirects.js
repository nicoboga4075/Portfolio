// Writes _redirects: rules derived from package.json "routes" (the "/" redirect,
// the pretty-url rewrites, the hidden-source-page 404s), then the fixed STATIC
// block. Runs via `npm run gen:redirects`, chained ahead of eleventy in build/dev
// (must exist before Eleventy; also re-runnable on its own).
//
// _redirects, not netlify.toml [[redirects]]: netlify.toml is parsed once at build
// start (a regen would land a deploy late), and literal from/to strings dodge
// Netlify placeholders not matching the _en / _fr suffix.

const fs = require("node:fs");
const path = require("node:path");
const { locales, defaultLang } = require("./package.json").routes;
// The sections, the pages of the root besides the home (blog, policy, terms), from the files themselves
const sections = require("./resolve-sections")(__dirname, defaultLang);
// The projects with a page of their own, from the explore of their _data/projects.json card
const projects = require("./projects/project-pages")(JSON.parse(fs.readFileSync(path.join(__dirname, "_data", "projects.json"), "utf8")).cards);
const langs = Object.keys(locales);

// pretty url -> real file (rewrite, 200). No source file exists at these paths, so no force flag.
const rewrites = [
    ...langs.map(lang => [`/${lang}`, `/index_${lang}.html`]),
    ...sections.flatMap(slug =>
        langs.map(lang => [`/${lang}/${slug}`, `/${slug}_${lang}.html`])),
    ...projects.flatMap(slug =>
        langs.map(lang => [`/${lang}/${slug}`, `/projects/${slug}_${lang}.html`]))
];

// Real deploy-root files to block directly (/index_en.html, /blog_fr.html, ...).
const hiddenPrefixes = ["index", ...sections];

const STATIC = `# The 404 page itself must not be reachable directly with a 200
/404.html /404 404!
/404 /404.html 404!

# Public assets nested under an otherwise-blocked directory (first match wins)
/docs/public/* /docs/public/:splat 200

# --- Un-rendered source directories --------------------------------------
/articles/* /404.html 404!
/projects/* /404.html 404!

# --- Markdown docs (static serving is case-insensitive, block both cases) -
/changelog.md /404.html 404!
/CHANGELOG.md /404.html 404!
/contributing.md /404.html 404!
/CONTRIBUTING.md /404.html 404!
/readme.md /404.html 404!
/README.md /404.html 404!
/security.md /404.html 404!
/SECURITY.md /404.html 404!
/robot_framework.md /404.html 404!
/ROBOT_FRAMEWORK.md /404.html 404!
/license /404.html 404!
/LICENSE /404.html 404!

# --- Build / tooling config and scripts at the deploy root ---------------
/.eleventy.js /404.html 404!
/.gitattributes /404.html 404!
/.gitignore /404.html 404!
/.htmlvalidate.json /404.html 404!
/.stylelintrc.json /404.html 404!
/netlify.toml /404.html 404!
/package.json /404.html 404!
/package-lock.json /404.html 404!
/tsconfig.json /404.html 404!
/eslint.config.mjs /404.html 404!
/jest.config.js /404.html 404!
/playwright.config.js /404.html 404!
/capacitor.config.json /404.html 404!
/sonar-project.properties /404.html 404!
/changelog.hbs /404.html 404!
/gen-redirects.js /404.html 404!
/uglify-code.js /404.html 404!
/dev-watch.js /404.html 404!
/html-validate-nunjucks.js /404.html 404!
/update-version.js /404.html 404!
/hide-folders.js /404.html 404!
/resolve-sections.js /404.html 404!
/.hidden /404.html 404!
/_redirects /404.html 404!
/_headers /404.html 404!

# --- Directories that must never be public ------------------------------
/node_modules/* /404.html 404!
/netlify/* /404.html 404!
/_includes/* /404.html 404!
/tests/* /404.html 404!
/reports/* /404.html 404!
/logs/* /404.html 404!
/docs/* /404.html 404!
/.github/* /404.html 404!
/.gitlab/* /404.html 404!
/.claude/* /404.html 404!`;

// The Jest tests of js/ sit next to the scripts and production publishes the repository root: each one gets its own 404, since a _redirects splat only ends a path (no /js/*.test.js)
const jsDir = path.join(__dirname, "js");
const jsTests = fs.existsSync(jsDir) ? fs.readdirSync(jsDir).filter(file => file.endsWith(".test.js")).sort() : [];

const out = [
    "# ---------------------------------------------------------------------------",
    "# Generated by gen-redirects.js from package.json - do not edit by hand.",
    "# Run `npm run gen:redirects` after editing package.json routes (also on build).",
    "# ---------------------------------------------------------------------------",
    "",
    "# Home",
    `/ /${defaultLang} 301!`,
    "",
    "# Pretty urls -> the real *_<lang>.html file (rewrite)",
    ...rewrites.map(([from, to]) => `${from} ${to} 200`),
    "",
    "# --- Un-rendered source pages (real files live in the deploy root) --------",
    ...hiddenPrefixes.map(prefix => `/${prefix}_* /404.html 404!`),
    "",
    "# --- Jest tests next to the site scripts (js/ is published as is) --------",
    ...jsTests.map(file => `/js/${file} /404.html 404!`),
    "",
    STATIC
];

fs.writeFileSync(path.join(__dirname, "_redirects"), out.join("\n").trimEnd() + "\n", "utf-8");
console.warn(`_redirects regenerated: ${rewrites.length} rewrites + static block`);
